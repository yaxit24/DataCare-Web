def load_catalog() -> dict[str, dict]:
    rows = {}
    for line in (REPO / 'docs/handbook/menu-catalog.jsonl').read_text(encoding='utf-8').splitlines():
        if line.strip():
            row = json.loads(line)
            rows[row['id']] = row
    return rows


def lite_rows() -> list[dict]:
    text = (REPO / 'docs/handbook/web/standard-progress.md').read_text(encoding='utf-8')
    block = text.split('## Lite')[1].split('## Basic')[0]
    out = []
    for line in block.splitlines():
        if line.startswith('| ') and not line.startswith('| Tab') and not line.startswith('|---'):
            c = [x.strip() for x in line.strip().strip('|').split('|')]
            out.append({'tab': c[0], 'menu': c[1], 'module': c[4], 'state': c[5], 'open': c[6]})
    return out


def status_of(row: dict, catalog_row: dict, snap: dict) -> tuple[str, str]:
    """Return (status, evidence text)."""
    module = None if row['module'] == '—' else MODULE_ALIAS.get(row['module'], row['module'])
    if not catalog_row.get('ui'):
        return 'MISSING', 'no web screen listed in the catalog'
    if module is None:
        return 'NOT YET VERIFIED', 'no browser feature module'
    s = snap.get(module)
    if s is None:
        return 'NOT YET VERIFIED', f'module `{module}` is not in the run snapshot'
    text = f"`{module}`: {s['passed']} passed, {s['failed']} failed, {s['blocked']} blocked of {s['applicable']} applicable"
    if s['failed']:
        return 'BROKEN', text
    if catalog_row['status'] == 'CONTAINED' or (s['applicable'] and s['blocked'] * 2 >= s['applicable']):
        return 'BLOCKED', text
    return 'PARTIAL', text


def cell(text: str, limit: int = 230) -> str:
    text = re.sub(r'\s+', ' ', text).replace('|', '/').strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + '…'


def build() -> str:
    catalog = load_catalog()
    snap = json.loads((PARITY / 'run-snapshot.json').read_text(encoding='utf-8'))
    own = json.loads((PARITY / 'ownership.json').read_text(encoding='utf-8'))
    modules, meta = snap['modules'], snap['meta']
    lines = [
        '# Lite edition feature matrix',
        '',
        f"Generated by `docs/parity/build_matrix.py` from the menu catalog, the progress page and `docs/parity/run-snapshot.json`"
        f" (feature run of {meta['date']} on commit `{meta['commit']}`). Do not edit by hand: change an input and regenerate.",
        'Status authority stays in `docs/master-parity-plan-2026-09-29/execution-backlog.json`; this table is a view.',
        '',
        '**Desktop reference limit.** The desktop is available as decompiled C# source (`unified/src/csharp/DataCareNext/`),'
        ' 1,069 tutorial-video keyframes and 254 extracted report XML specs. The Windows binaries, `.rpt` templates and the'
        ' SQL Server backup are Git LFS pointers (about 130 bytes each), there is no Windows runtime and no desktop screenshot'
        ' set to diff against. So *Desktop Behavior* below is what the source and the catalog say, and **desktop-match coverage'
        ' is 0% for every row**. No row can be VERIFIED PARITY until a case runs on the original Windows desktop.',
        '',
    ]
    counts: dict[str, int] = {}
    body = []
    for row in lite_rows():
        cid = f"{row['tab']}/{row['menu']}"
        crow = catalog[cid]
        status, evidence = status_of(row, crow, modules)
        counts[status] = counts.get(status, 0) + 1
        prio, why = PRIORITY.get(cid, ('P3', 'nothing open beyond desktop-runtime comparison'))
        owner = own.get(cid, own.get('_default', 'unowned'))
        body.append(
            f"| {row['menu']} | {cell(crow['purpose'], 150)} | {cell(', '.join(crow['ui']) or 'none', 70)} | "
            f"{cell(crow['gaps'], 260)} | {prio}: {cell(why, 90)} | {cell(owner, 90)} | {status} | {cell(evidence, 120)} |"
        )
    lines += [
        '## Totals',
        '',
        '| Status | Menus |',
        '|---|---:|',
        *[f'| {s} | {counts.get(s, 0)} |' for s in
          ('VERIFIED PARITY', 'PARTIAL', 'MISSING', 'BROKEN', 'BLOCKED', 'NOT YET VERIFIED')],
        f"| **Lite menus** | **{sum(counts.values())}** |",
        '',
        'NOT YET VERIFIED is not counted as complete. VERIFIED PARITY is 0 because no catalog row is FULL and no case has run on the desktop.',
        '',
        '## Matrix',
        '',
        '| Feature | Desktop Behavior | Web Behavior (screen) | Gap | Priority | Owner | Status | Test Evidence |',
        '|---|---|---|---|---|---|---|---|',
        *body,
        '',
        '## Rules used',
        '',
        '- **Status** is assigned in this order: BROKEN (an executed case fails), BLOCKED (half or more of the applicable cases are blocked, or the'
        ' catalog row is CONTAINED), NOT YET VERIFIED (no module), MISSING (no web screen), else PARTIAL.',
        '- A failing case outranks blocked ones, so Company shows BROKEN although most of its cases are blocked. Sales Order and Order Report share the'
        ' `sales-order` module, so one failing case (`sales-order.create.scheme-tender`, G206) makes both rows BROKEN: that is one defect, not two.',
        '- **Priority** is written by a person per menu in `PRIORITY` (P0 data integrity, security or business correctness; P1 missing core'
        ' functionality or broken workflow; P2 behavioural or UI/UX mismatch; P3 minor, or not provable without a desktop runtime).',
        '- **Owner** comes from `docs/parity/ownership.json`, which records open pull requests, branches and claims at the date in'
        ' `AGENT-PROGRESS.md`. A menu with no entry is `unowned`.',
        '- **Test Evidence** counts cases of the named feature module in the dated run. A blocked case is not a pass. See `TEST-EVIDENCE.md`.',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    text = build()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            print('docs/parity/FEATURE-MATRIX.md is stale: run python3 docs/parity/build_matrix.py')
            return 1
        print('FEATURE_MATRIX_OK')
        return 0
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT.relative_to(REPO)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
