#!/usr/bin/env python3
"""Generate docs/parity/FEATURE-MATRIX.md for the 49 Lite menus.

Inputs (all committed; nothing is guessed):
  docs/handbook/menu-catalog.jsonl            desktop behaviour, web surface, remaining gaps, owners
  docs/handbook/web/standard-progress.md      menu -> feature module, module state (generated by `pnpm progress`)
  docs/parity/run-snapshot.json               case counts per module from one dated full feature run
  docs/parity/ownership.json                  who holds each menu now (hand-kept; see AGENT-PROGRESS.md)

Usage:
  python3 docs/parity/build_matrix.py            # rewrite FEATURE-MATRIX.md
  python3 docs/parity/build_matrix.py --check    # exit 1 if FEATURE-MATRIX.md is stale

Status vocabulary (the task's six values) and how each is assigned, in this order:
  BROKEN              an executed browser case fails (the failure is a baselined defect)
  BLOCKED             at least half of the module's applicable cases are blocked, or the catalog row is CONTAINED
  NOT YET VERIFIED    no browser feature module covers the menu
  PARTIAL             a module covers it, nothing executed fails, at least one gap or blocked case remains
  VERIFIED PARITY     never assigned here: it needs a catalog row of FULL, which needs a desktop-runtime comparison
                      that does not exist (desktop match is 0% for every menu)
  MISSING             the catalog row lists no web screen for the menu

Priority (P0..P3) comes from `PRIORITY` below, written by a person from the catalog gap text and the desktop source,
not computed. A menu with nothing open is not listed there and shows P3.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PARITY = REPO / 'docs' / 'parity'
OUT = PARITY / 'FEATURE-MATRIX.md'
MODULE_ALIAS = {'users-rights': 'users'}

