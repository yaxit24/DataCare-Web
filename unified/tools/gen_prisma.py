#!/usr/bin/env python3
"""
gen_prisma.py  —  Phase 1 / Task 7
Generate a Prisma schema (+ RLS SQL) for PostgreSQL from the data-model catalog.
Implements Requirement 5 (data layer mirroring the desktop model) + ADR-0001 type policy.

Rules:
  - Model per table (@@map to exact table name); scalar fields keep exact column names.
  - SQL Server FLOAT for money/weight -> Decimal @db.Decimal(p,s) (NUMERIC), NOT float.
  - VARCHAR(n)->String @db.VarChar(n); DATE->DateTime @db.Date; DATETIME->@db.Timestamp;
    image->Bytes; INT->Int; BIT->Boolean; unknown->String (flagged).
  - tenant_id added to EVERY model (RLS partition). Composite @@id = [tenantId, ...primaryKey]
    when a PK is known; otherwise a surrogate row_id BigInt @id is added + @@index([tenantId]).
  - rls.sql enables RLS + a tenant policy per table (uses current_setting('app.tenant_id')).
Outputs: web/packages/db/prisma/schema.prisma, web/packages/db/prisma/rls.sql
Re-run after any authoritative (Docker mssql) refinement of data-model.json.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import re
from pathlib import Path

WEIGHT_TOKENS = ("GWT", "NWT", "WT", "FINE", "TOUCH", "WEIGHT", "MINO", "WASTAGE", "WEST", "LOSS")
AMOUNT_TOKENS = ("AMT", "AMOUNT", "RATE", "VALUE", "COST", "COMM", "DISC", "TOT", "NET",
                 "CASH", "CARD", "CHQ", "ADV", "KASAR", "ROF", "PROF", "MRP", "LIMIT", "BAL")
PCT_TOKENS = ("PRC", "PERCENT")
PCS_TOKENS = ("PCS", "QTY")


def classify_float(col: str) -> tuple[str, str]:
    """Return (prismaType, dbAttr) for a FLOAT column based on its name."""
    u = col.upper()
    if any(t in u for t in PCT_TOKENS):
        return "Decimal", "@db.Decimal(9, 4)"
    if "FINE" in u:
        return "Decimal", "@db.Decimal(14, 3)"
    if any(t in u for t in WEIGHT_TOKENS):
        return "Decimal", "@db.Decimal(14, 3)"
    if any(t in u for t in PCS_TOKENS):
        return "Decimal", "@db.Decimal(12, 3)"
    if any(t in u for t in AMOUNT_TOKENS):
        return "Decimal", "@db.Decimal(18, 2)"
    return "Float", ""  # genuine non-monetary float


def map_type(col: dict) -> tuple[str, str]:
    t = (col.get("type") or "unknown").upper()
    n = col["name"]
    length = col.get("length")
    if t in ("VARCHAR", "NVARCHAR", "CHAR", "NCHAR"):
        return "String", f"@db.VarChar({length})" if length else "@db.VarChar(255)"
    if t in ("TEXT", "NTEXT"):
        return "String", "@db.Text"
    if t == "FLOAT" or t == "REAL":
        return classify_float(n)
    if t in ("DECIMAL", "NUMERIC", "MONEY"):
        return "Decimal", f"@db.Decimal({length or 18}, 2)"
    if t in ("INT", "INTEGER", "SMALLINT", "TINYINT", "BIGINT"):
        return ("BigInt", "@db.BigInt") if t == "BIGINT" else ("Int", "")
    if t == "BIT":
        return "Boolean", ""
    if t in ("DATE",):
        return "DateTime", "@db.Date"
    if t in ("DATETIME", "DATETIME2", "SMALLDATETIME", "TIMESTAMP"):
        return "DateTime", "@db.Timestamp(6)"
    if t in ("IMAGE", "VARBINARY", "BINARY"):
        return "Bytes", ""
    return "String", "@db.VarChar(255)"  # unknown -> safe string (flagged via comment)


def field_line(col: dict, required: bool) -> str:
    ptype, dbattr = map_type(col)
    opt = "" if required else "?"
    bits = [f"  {col['name']} {ptype}{opt}"]
    if dbattr:
        bits.append(dbattr)
    if (col.get("type") or "").lower() in ("", "unknown"):
        bits.append("// TODO type: confirm via Docker mssql pass")
    return " ".join(bits)


def emit_model(name: str, tbl: dict) -> str:
    cols = tbl["columns"]
    col_names = {c["name"] for c in cols}
    pk = [c for c in tbl.get("primaryKey", []) if c in col_names]
    has_pk = bool(pk) and len(pk) == len(tbl.get("primaryKey", []))
    lines = [f"model {name} {{"]
    lines.append('  tenantId String @map("tenant_id") @db.VarChar(24)')
    if not has_pk:
        lines.append('  rowId BigInt @id @default(autoincrement()) @map("row_id")')
    for c in cols:
        required = has_pk and c["name"] in pk
        lines.append(field_line(c, required=required))
    if has_pk:
        lines.append(f"  @@id([tenantId, {', '.join(pk)}])")
    else:
        lines.append("  @@index([tenantId])")
    lines.append(f'  @@map("{name}")')
    lines.append("}")
    return "\n".join(lines)


def build_schema(model: dict) -> str:
    header = (
        "// AUTO-GENERATED by unified/tools/gen_prisma.py from project-memory/catalogs/data-model.json\n"
        f"// Generated {_dt.datetime.now().isoformat(timespec='seconds')}. Do not edit by hand; re-run the generator.\n\n"
        'datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n\n'
        'generator client {\n  provider = "prisma-client-js"\n}\n\n'
    )
    tables = model["tables"]
    bodies = [emit_model(name, tables[name]) for name in sorted(tables)]
    return header + "\n\n".join(bodies) + "\n"


def build_rls(model: dict) -> str:
    out = ["-- AUTO-GENERATED RLS policies (Task 7). Apply after `prisma migrate`.",
           "-- Session must set: SELECT set_config('app.tenant_id', $1, false);", ""]
    for name in sorted(model["tables"]):
        out.append(f'ALTER TABLE "{name}" ENABLE ROW LEVEL SECURITY;')
        out.append(f'ALTER TABLE "{name}" FORCE ROW LEVEL SECURITY;')
        out.append(
            f'CREATE POLICY tenant_isolation ON "{name}" USING '
            f"(tenant_id = current_setting('app.tenant_id', true));"
        )
        out.append("")
    return "\n".join(out)


def main() -> int:
    here = Path(__file__).resolve()
    repo = here.parents[2]
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-model", default=str(repo / "project-memory" / "catalogs" / "data-model.json"))
    ap.add_argument("--out-dir", default=str(repo / "web" / "packages" / "db" / "prisma"))
    args = ap.parse_args()
    model = json.loads(Path(args.data_model).read_text())
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "schema.prisma").write_text(build_schema(model), encoding="utf-8")
    (out / "rls.sql").write_text(build_rls(model), encoding="utf-8")
    print(f"schema.prisma + rls.sql -> {out}")
    print(f"  models: {len(model['tables'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
