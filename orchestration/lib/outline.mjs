// Form index: a deterministic map of one decompiled desktop form, so a worker reads line ranges instead of a
// 5,000-33,000 line file. No model is involved; every row carries the source line.
import fs from 'node:fs';
import path from 'node:path';

const DECL = /^\t{1,2}(?:public|private|protected|internal)\s+(?:(?:static|override|virtual|async|sealed|new|unsafe)\s+)*(?:[\w<>[\],.?]+\s+)?(\w+)\s*\(([^)]*)\)\s*$/;
const CAPTION = /^\s*(?:this\.)?(\w+)\.(?:Text|HeaderText) = "((?:[^"\\]|\\.)*)";/;
const MESSAGE = /(?:MsgBox|MessageBox\.Show)\(\s*(?:\(object\))?\s*"((?:[^"\\]|\\.)*)"/g;
const SQL = /\b(INSERT\s+INTO|UPDATE|DELETE\s+FROM|FROM|JOIN)\s+\[?([A-Za-z_][A-Za-z0-9_]{2,})\]?/gi;
const REPORT = /"([A-Za-z0-9_ ]+\.rpt)"/gi;
const KEY = /\bKeys\.(\w+)|e\.KeyCode|e\.KeyChar|SendKeys\.Send/;

function kindOf(name, params) {
  if (name === 'InitializeComponent') return 'designer';
  if (/\bsender\b/.test(params)) {
    const m = name.match(/_([A-Za-z0-9]+)$/);
    return m ? `event:${m[1]}` : 'event';
  }
  return 'method';
}

export function outlineForm(file) {
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  const members = [];
  lines.forEach((line, i) => {
    const m = line.match(DECL);
    if (m) members.push({ name: m[1], start: i + 1, end: lines.length, kind: kindOf(m[1], m[2]), keys: false });
  });
  members.forEach((mem, i) => {
    if (members[i + 1]) mem.end = members[i + 1].start - 1;
  });
  const memberAt = (lineNo) => {
    let found = null;
    for (const mem of members) {
      if (mem.start <= lineNo) found = mem;
      else break;
    }
    return found;
  };
  const captions = [];
  const messages = [];
  const tables = new Map();
  const reports = new Map();
  lines.forEach((line, i) => {
    const no = i + 1;
    const cap = line.match(CAPTION);
    if (cap && cap[2].trim()) captions.push({ control: cap[1], text: cap[2], line: no });
    for (const m of line.matchAll(MESSAGE)) messages.push({ text: m[1], line: no, member: memberAt(no)?.name || '' });
    if (line.includes('"')) {
      for (const m of line.matchAll(SQL)) {
        const op = m[1].toUpperCase().replace(/\s+/g, ' ');
        const table = m[2].toUpperCase();
        if (['THE', 'AND', 'SET', 'NOT'].includes(table)) continue;
        const t = tables.get(table) || { writes: [], reads: [] };
        (op === 'FROM' || op === 'JOIN' ? t.reads : t.writes).push(`${op === 'FROM' || op === 'JOIN' ? '' : `${op.split(' ')[0]} `}${no}`);
        tables.set(table, t);
      }
      for (const m of line.matchAll(REPORT)) reports.set(m[1], [...(reports.get(m[1]) || []), no]);
    }
    if (KEY.test(line)) {
      const mem = memberAt(no);
      if (mem) mem.keys = true;
    }
  });
  return { file: path.basename(file), lineCount: lines.length, members, captions, messages, tables, reports };
}

const cell = (s) => String(s).replace(/\|/g, '\\|').slice(0, 140);
const some = (list, n = 8) => (list.length > n ? `${list.slice(0, n).join(', ')}, +${list.length - n} more` : list.join(', '));

export function renderOutline(o) {
  const out = [];
  out.push(`# Form index: ${o.file} (${o.lineCount} lines)`, '');
  out.push('Generated by `node orchestration/bin/orch.mjs outline`. It is a map, not an authority: open the cited lines');
  out.push('before you state what the desktop does. Lines are 1-based lines of the decompiled source.', '');
  out.push(`Members: ${o.members.length} · captions: ${o.captions.length} · messages: ${o.messages.length} · tables: ${o.tables.size} · report templates: ${o.reports.size}`, '');
  out.push('## Members', '', '| Member | Lines | Kind | Keys |', '|---|---|---|---|');
  for (const m of o.members) out.push(`| ${cell(m.name)} | ${m.start}-${m.end} | ${m.kind} | ${m.keys ? 'yes' : ''} |`);
  out.push('', '## Tables touched', '', '| Table | Writes (statement line) | Reads (line) |', '|---|---|---|');
  for (const [name, t] of [...o.tables].sort()) out.push(`| ${name} | ${some(t.writes)} | ${some(t.reads)} |`);
  out.push('', '## Message texts (copy verbatim, spelling included)', '', '| Line | Member | Text |', '|---|---|---|');
  for (const m of o.messages) out.push(`| ${m.line} | ${cell(m.member)} | ${cell(m.text)} |`);
  out.push('', '## Captions', '', '| Line | Control | Text |', '|---|---|---|');
  for (const c of o.captions) out.push(`| ${c.line} | ${cell(c.control)} | ${cell(c.text)} |`);
  if (o.reports.size) {
    out.push('', '## Report templates named', '', '| Template | Lines |', '|---|---|');
    for (const [name, at] of [...o.reports].sort()) out.push(`| ${cell(name)} | ${some(at)} |`);
  }
  return `${out.join('\n')}\n`;
}
