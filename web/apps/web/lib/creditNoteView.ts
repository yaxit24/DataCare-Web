export const creditNoteValue = (value: unknown): string =>
  value == null ? 'Not set' : value === '' ? 'Blank' : String(value);

export function creditNoteComponents(
  document: CreditNoteDocument,
  line: CreditNoteRow,
): CreditNoteRow[] {
  // Desktop EInvoice joins through OLD_SRNO; older web entries may have only SR_NO.
  return document.components.filter(
    (component) => String(component.parentSrNo) === String(line.SR_NO),
  );
}
