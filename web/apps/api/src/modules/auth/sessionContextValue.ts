/**
 * Strict values for the prospective server session-context protocol.
 * Parsing supplies no session, permission, mode, freshness or retry authority.
 */
export const SESSION_LEDGER_CONTEXT_VERSION = 'server-session-ledger-context-v1' as const;
export const MAX_CONTEXT_EPOCH = '9223372036854775807' as const;

declare const contextEpochBrand: unique symbol;
export type ContextEpoch = string & { readonly [contextEpochBrand]: true };

declare const contextSelectionIdBrand: unique symbol;
export type ContextSelectionId = string & { readonly [contextSelectionIdBrand]: true };

export type UnknownLedgerReason =
  | 'vendor-authority-unresolved'
  | 'legacy-session-uninitialized'
  | 'scope-incomplete';

export interface UnknownSessionLedgerContext {
  readonly version: typeof SESSION_LEDGER_CONTEXT_VERSION;
  readonly status: 'unknown';
  readonly mode: null;
  readonly reason: UnknownLedgerReason;
}

type ContextValueError =
  | 'invalid-context-epoch'
  | 'context-epoch-exhausted'
  | 'invalid-ledger-context'
  | 'invalid-context-selection-id';

export type ContextValueResult<T> =
  | Readonly<{ status: 'ready'; value: T }>
  | Readonly<{ status: 'invalid'; code: ContextValueError }>;

const ready = <T>(value: T): ContextValueResult<T> => Object.freeze({ status: 'ready', value });
const invalid = (code: ContextValueError): ContextValueResult<never> =>
  Object.freeze({ status: 'invalid', code });

/** Canonical positive signed PostgreSQL BIGINT, carried as text without Number conversion. */
export function parseContextEpoch(value: unknown): ContextValueResult<ContextEpoch> {
  if (
    typeof value !== 'string' ||
    value.length === 0 ||
    value.length > MAX_CONTEXT_EPOCH.length ||
    value[0] === '0' ||
    /[^0-9]/.test(value) ||
    (value.length === MAX_CONTEXT_EPOCH.length && value > MAX_CONTEXT_EPOCH)
  ) {
    return invalid('invalid-context-epoch');
  }
  return ready(value as ContextEpoch);
}

/** Exhaustion is a refusal, never a wrapped generation or a reset to the initial epoch. */
export function nextContextEpoch(value: unknown): ContextValueResult<ContextEpoch> {
  const parsed = parseContextEpoch(value);
  if (parsed.status !== 'ready') return parsed;
  if (parsed.value === MAX_CONTEXT_EPOCH) return invalid('context-epoch-exhausted');
  return ready((BigInt(parsed.value) + 1n).toString() as ContextEpoch);
}

/** Initial web transport profile: lowercase UUIDv4 generated by crypto.randomUUID. */
export function parseContextSelectionId(value: unknown): ContextValueResult<ContextSelectionId> {
  if (
    typeof value !== 'string' ||
    value.length !== 36 ||
    !/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value)
  ) {
    return invalid('invalid-context-selection-id');
  }
  return ready(value as ContextSelectionId);
}

/**
 * Accept only a complete plain data envelope. Reading descriptors avoids invoking getters;
 * copied scalar values prevent later caller mutation from changing the returned observation.
 */
export function parseUnknownSessionLedgerContext(
  value: unknown,
): ContextValueResult<UnknownSessionLedgerContext> {
  try {
    if (value === null || typeof value !== 'object') return invalid('invalid-ledger-context');
    const prototype = Object.getPrototypeOf(value);
    if (prototype !== Object.prototype && prototype !== null) return invalid('invalid-ledger-context');
    const fields = ['version', 'status', 'mode', 'reason'] as const;
    const keys = Reflect.ownKeys(value);
    if (keys.length !== fields.length || keys.some((key) => !fields.some((field) => field === key))) {
      return invalid('invalid-ledger-context');
    }
    const data: Record<string, unknown> = Object.create(null);
    for (const field of fields) {
      const descriptor = Object.getOwnPropertyDescriptor(value, field);
      if (!descriptor || !descriptor.enumerable || !Object.hasOwn(descriptor, 'value')) {
        return invalid('invalid-ledger-context');
      }
      data[field] = descriptor.value;
    }
    if (
      data.version !== SESSION_LEDGER_CONTEXT_VERSION ||
      data.status !== 'unknown' ||
      data.mode !== null ||
      (data.reason !== 'vendor-authority-unresolved' &&
        data.reason !== 'legacy-session-uninitialized' &&
        data.reason !== 'scope-incomplete')
    ) {
      return invalid('invalid-ledger-context');
    }
    return ready(
      Object.freeze({
        version: SESSION_LEDGER_CONTEXT_VERSION,
        status: 'unknown',
        mode: null,
        reason: data.reason,
      }),
    );
  } catch {
    // Reflection on an invalid exotic object may throw. It never supplies a known mode.
    return invalid('invalid-ledger-context');
  }
}
