import type { SettingTable } from './settingsInventory.js';

/**
 * The settings catalog: one typed descriptor per configurable column of CO_SET and CO_SET_NEW.
 *
 * GENERATED from two verified sources and checked in:
 *   - `settingsInventory.ts` (information_schema) supplies the key set, storage shape and real width.
 *   - `project-memory/parity/DESKTOP-SETTINGS-CONTRACT.json` supplies each control's option list and its
 *     persistence rule, extracted by `desktop_settings_contract.py`.
 *
 * Descriptors are identified by `id = "<table>.<column>"`, not by column name. `COUNTRY_ID` genuinely
 * exists in BOTH tables and the desktop writes both with different defaults — `CO_SET_NEW.COUNTRY_ID='91'`
 * (`Ac_Image.cs:7163`) and `CO_SET.COUNTRY_ID='971'` (`Mfg_Module.cs:1506`). Keying by column name alone
 * silently dropped one of them.
 *
 * STORAGE SHAPE WINS over the option-list shape. `TOT_AMT_ROF` offers the choices 0/1/2 but is an INTEGER
 * column, so it is typed `number` with an allowed-value list rather than a string enum; typing it as an enum
 * would write the text '0' into an integer column.
 *
 * Options carry a display `label` and a separate persisted `value` because the desktop stores a combo's
 * FIRST CHARACTER for most settings (`Strings.Mid(cboLbrType.Text, 1, 1)`: "Net Wise" becomes "N"), the
 * FULL TEXT for a few, and a NUMBER for others. Desktop misspellings ("Gorss Wise", "Mobile Mathod",
 * "Whout Row Short") are preserved verbatim because those strings are the contract.
 *
 * `unknownOptions: true` marks a setting whose finite domain is NOT proven from desktop source; it stays
 * free text rather than inventing a dropdown. 35 descriptors are in that state; the parity gate lets
 * that count fall and never rise.
 */
export interface SettingOption {
  label: string;
  value: string;
}

export interface SettingDescriptor {
  /** Stable identifier `<table>.<column>`; unique even when a column name appears in both tables. */
  id: string;
  key: string;
  table: SettingTable;
  type: 'boolean' | 'enum' | 'number' | 'date' | 'text';
  label: string;
  hint?: string;
  options?: SettingOption[];
  /**
   * The options are presets of an editable combo, not a closed list (G177). No setting form sets a DropDownStyle, so
   * every desktop setting combo accepts typed text, and these save it as `Val(Text)` (UT_SETTING.cs:5059,
   * UT_SETTING_MAIN.cs:9120, :9148, :9300). Any number is accepted; an integer column takes whole numbers only.
   */
  editable?: 'number' | 'integer';
  maxLength?: number;
  /** No authoritative desktop option list found; rendered as text pending evidence. */
  unknownOptions?: true;
  surface: 'UT_SETTING' | 'UT_SETTING_MAIN' | 'UT_SET_ADMIN' | 'SCHEMA_ONLY';
}

