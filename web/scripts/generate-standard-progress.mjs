#!/usr/bin/env node
/**
 * Generate `docs/handbook/web/standard-progress.md`: delivery progress of the Standard edition, tier by tier
 * (D31, D32). Lite comes first, then the menus Basic adds, then the menus Standard adds, as the owner ordered.
 *
 * Sources:
 *   - `docs/handbook/menu-editions.json`: each desktop menu with its edition (desktop MENU_DATA).
 *   - `docs/handbook/menu-catalog.jsonl`: each menu's web routes (`ui`) and catalog status.
 *   - `web/apps/web/test/features/coverage-map.json`: which feature module covers which page.
 *   - `web/apps/web/test/features/baseline.json`: the open (baselined) defects of each feature module.
 *
 * A menu is DONE when its catalog row is FULL and a feature module covers it with no open defect. The page reports
 * the other states too, so progress is visible before a menu is done.
 *
 *   node scripts/generate-standard-progress.mjs          # write the page
 *   node scripts/generate-standard-progress.mjs --check  # exit 1 when the committed page is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const repoRoot = resolve(webRoot, '..');
const OUTPUT = resolve(repoRoot, 'docs/handbook/web/standard-progress.md');
const TIERS = [
  { code: 'L', name: 'Lite', note: 'first, D32' },
  { code: 'B', name: 'Basic', note: 'added by Basic' },
  { code: 'S', name: 'Standard', note: 'added by Standard' },
];

const read = (path) => readFileSync(resolve(repoRoot, path), 'utf8');
const menus = JSON.parse(read('docs/handbook/menu-editions.json')).menus;
const catalog = new Map(
  read('docs/handbook/menu-catalog.jsonl')
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => JSON.parse(line))
    .map((row) => [row.id, row]),
);
const coverage = JSON.parse(read('web/apps/web/test/features/coverage-map.json')).modules;
const baseline = JSON.parse(read('web/apps/web/test/features/baseline.json'));

/** `web/apps/web/app/(app)/txn/sales/page.tsx` → `/txn/sales`; route groups in parentheses are dropped. */
const routeOfPage = (file) => {
  const match = /^web\/apps\/web\/app\/(.+)\/page\.tsx$/.exec(file);
  if (!match) return null;
  return `/${match[1]
    .split('/')
    .filter((part) => !/^\(.*\)$/.test(part))
    .join('/')}`;
};
/** coverage-map key (camelCase) → feature id used by baseline.json (kebab-case). */
const featureId = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const moduleByRoute = new Map();
for (const [key, entry] of Object.entries(coverage)) {
  for (const file of entry.covers ?? []) {
    const route = routeOfPage(file);
    if (route) moduleByRoute.set(route, featureId(key));
  }
}
const basePath = (href) => (href.split('?')[0] ?? '').replace(/\/+$/, '') || '/';

const rows = [];
for (const menu of menus) {
  if (!menu.visible || menu.separator) continue;
  const tier = TIERS.find((t) => t.code === menu.edition);
  if (!tier) continue;
  const entry = catalog.get(menu.catalogId);
  const routes = [...new Set((entry?.ui ?? []).map((href) => href))];
  const modules = [
    ...new Set(routes.map((href) => moduleByRoute.get(basePath(href))).filter(Boolean)),
  ];
  const open = modules.flatMap((id) => baseline[id] ?? []);
  const gaps = [...new Set(open.map((item) => item.gap))].sort();
  const status = entry?.status ?? 'UNMAPPED';
  const state =
    status === 'FULL' && modules.length && !open.length
      ? 'done'
      : modules.length && !open.length
        ? 'module green'
        : modules.length
          ? `module, ${open.length} open`
          : 'no module';
  rows.push({
    tier: tier.code,
    tab: menu.tab,
    menu: menu.menu,
    routes,
    status,
    modules,
    gaps,
    open,
    state,
  });
}

const count = (list, predicate) => list.filter(predicate).length;
const out = [];
out.push('# Standard edition — delivery progress by edition tier');
out.push('');
out.push(
  'Generated by `web/scripts/generate-standard-progress.mjs` from `docs/handbook/menu-editions.json`, ' +
    '`docs/handbook/menu-catalog.jsonl` and the feature E2E coverage map and baseline. Do not edit by hand; ' +
    'regenerate after a module, a baseline entry or a catalog status changes.',
);
out.push('');
out.push(
  'Order (D31, D32): every Lite menu works end to end like the desktop first, then the menus Basic adds, then the ' +
    'menus Standard adds; the higher editions follow Standard. A menu is **done** when its catalog row is FULL and a ' +
    'browser feature module covers it with no open defect.',
);
out.push('');
out.push('| Tier | Menus | With a feature module | Module with no open defect | Done |');
out.push('|---|---:|---:|---:|---:|');
let cumulative = 0;
for (const tier of TIERS) {
  const list = rows.filter((row) => row.tier === tier.code);
  cumulative += list.length;
  out.push(
    `| ${tier.name} (${tier.note}) | ${list.length} | ${count(list, (r) => r.modules.length)} | ` +
      `${count(list, (r) => r.modules.length && !r.open.length)} | ${count(list, (r) => r.state === 'done')} |`,
  );
}
out.push(
  `| **Standard total** | **${rows.length}** | **${count(rows, (r) => r.modules.length)}** | ` +
    `**${count(rows, (r) => r.modules.length && !r.open.length)}** | **${count(rows, (r) => r.state === 'done')}** |`,
);
out.push('');
for (const tier of TIERS) {
  const list = rows.filter((row) => row.tier === tier.code);
  out.push(`## ${tier.name} — ${list.length} menus (${tier.note})`);
  out.push('');
  out.push('| Tab | Menu | Web routes | Catalog | Feature module | State | Open gaps |');
  out.push('|---|---|---|---|---|---|---|');
  for (const row of list) {
    out.push(
      `| ${row.tab} | ${row.menu} | ${row.routes.map((r) => `\`${r}\``).join(', ') || '—'} | ${row.status} | ` +
        `${row.modules.join(', ') || '—'} | ${row.state} | ${row.gaps.join(', ') || '—'} |`,
    );
  }
  out.push('');
}
const text = `${out.join('\n').trimEnd()}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== text) {
    console.error('STANDARD_PROGRESS_STALE run: node scripts/generate-standard-progress.mjs');
    process.exit(1);
  }
  console.log('STANDARD_PROGRESS_OK');
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}: ${rows.length} menus`);
}
